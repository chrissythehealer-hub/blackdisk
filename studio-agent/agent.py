def new_id() -> str:
    return secrets.token_hex(12)


def now() -> float:
    return round(time.time(), 3)


# ====================================================================== tokens (mirror of src/lib/studio/token.ts)
def verify_token(secret: str, token: str | None, scope: str = "agent") -> bool:
    if not token or len(token) > 512:
        return False
    parts = token.split(".")
    if len(parts) != 3 or parts[0] != "v1":
        return False
    body = f"{parts[0]}.{parts[1]}"
    expected = base64.urlsafe_b64encode(hmac.new(secret.encode(), body.encode(), hashlib.sha256).digest()).rstrip(b"=").decode()
    if not hmac.compare_digest(expected, parts[2]):
        return False
    try:
        pad = "=" * (-len(parts[1]) % 4)
        payload = json.loads(base64.urlsafe_b64decode(parts[1] + pad))
    except (ValueError, TypeError):
        return False
    return payload.get("scope") == scope and isinstance(payload.get("exp"), (int, float)) and payload["exp"] > time.time()


# ====================================================================== state (one JSON file, atomic writes)
class Store:
    def __init__(self, data_dir: str):
        self.dir = data_dir
        self.path = os.path.join(data_dir, "state.json")
        for sub in ("uploads", "outputs"):
            os.makedirs(os.path.join(data_dir, sub), exist_ok=True)
        self.lock = threading.RLock()
        self.data = {"projects": {}, "jobs": {}, "uploads": {}}
        if os.path.exists(self.path):
            with open(self.path, encoding="utf-8") as f:
                self.data.update(json.load(f))
        if not self.data["projects"]:
            pid = new_id()
            self.data["projects"][pid] = {"id": pid, "name": "My first project", "created": now()}
            self.save()

    def save(self) -> None:
        with self.lock:
            tmp = self.path + ".tmp"
            with open(tmp, "w", encoding="utf-8") as f:
                json.dump(self.data, f, ensure_ascii=False, indent=1)
            os.replace(tmp, self.path)

    def file(self, kind: str, name: str) -> str:
        # Names are always generated by us (hex id + fixed extension) — never taken from the request.
        return os.path.join(self.dir, kind, name)


# ====================================================================== the agent
class Agent:
    def __init__(self, cfg: dict):
        self.cfg = cfg
        self.secret = cfg["secret"]
        self.origins = set(cfg.get("allowed_origins") or [])
        self.max_pending = int(cfg.get("max_pending", 6))
        data_dir = cfg.get("data_dir") or "studio-data"
        self.store = Store(data_dir if os.path.isabs(data_dir) else os.path.join(HERE, data_dir))
        self.comfy = ComfyClient(cfg.get("comfy_url", "http://127.0.0.1:8188"))
        self.ffprobe = shutil.which("ffprobe")

    # ------------------------------------------------------------ capabilities
    def capabilities(self) -> dict:
        out = {"agent": VERSION, "comfy": {"online": False}, "workflows": [], "limits": WAN22_LIMITS, "hardware": None}
        try:
            stats = self.comfy.system_stats()
        except ComfyError as e:
            out["comfy"]["error"] = str(e)
            out["guidance"] = hardware_guidance(None, None)
            for wf in WORKFLOWS.values():
                out["workflows"].append({**_public_wf(wf), "available": False, "reason": "ComfyUI is not running."})
            return out
        system = stats.get("system", {})
        dev = (stats.get("devices") or [{}])[0]
        vram = dev.get("vram_total")
        out["comfy"] = {"online": True, "version": system.get("comfyui_version"), "pytorch": system.get("pytorch_version"), "os": system.get("os")}
        out["hardware"] = {
            "gpu": dev.get("name"),
            "device_type": dev.get("type"),
            "vram_gb": round(vram / 1024**3, 1) if vram else None,
            "vram_free_gb": round(dev.get("vram_free", 0) / 1024**3, 1) if vram else None,
            "ram_gb": round(system.get("ram_total", 0) / 1024**3, 1) or None,
        }
        out["guidance"] = hardware_guidance(out["hardware"]["vram_gb"], dev.get("type"))

        installed: dict[str, set] = {}
        for loader, key, folder in (("UNETLoader", "unet_name", "diffusion_models"), ("CLIPLoader", "clip_name", "text_encoders"), ("VAELoader", "vae_name", "vae")):
            try:
                opts = self.comfy.object_info(loader)["input"]["required"][key][0]
                installed[folder] = set(opts) if isinstance(opts, list) else set()
            except (ComfyError, KeyError, IndexError, TypeError):
                installed[folder] = set()
        node_ok: dict[str, bool] = {}
        for wf in WORKFLOWS.values():
            missing_files = [f"models/{folder}/{name}" for folder, name in wf["files"].items() if name not in installed.get(folder, set())]
            missing_nodes = []
            for n in wf["nodes"]:
                if n not in node_ok:
                    try:
                        node_ok[n] = bool(self.comfy.object_info(n))
                    except ComfyError:
                        node_ok[n] = False
                if not node_ok[n]:
                    missing_nodes.append(n)
            reason = None
            if missing_nodes:
                reason = "Update ComfyUI — missing nodes: " + ", ".join(missing_nodes)
            elif missing_files:
                reason = "Model files not installed: " + ", ".join(missing_files)
            out["workflows"].append({**_public_wf(wf), "available": reason is None, "reason": reason})
        return out

    # ------------------------------------------------------------ uploads
    def save_upload(self, body: bytes, content_type: str) -> dict:
        ext = IMAGE_TYPES.get(content_type)
        if not ext:
            raise ValidationError("Upload a PNG, JPEG or WebP image.")
        sniff = (body[:8] == b"\x89PNG\r\n\x1a\n" and ext == ".png") or (body[:3] == b"\xff\xd8\xff" and ext == ".jpg") or (body[:4] == b"RIFF" and body[8:12] == b"WEBP" and ext == ".webp")
        if not sniff:
            raise ValidationError("That file is not a valid image of the declared type.")
        uid = new_id()
        with open(self.store.file("uploads", uid + ext), "wb") as f:
            f.write(body)
        rec = {"id": uid, "ext": ext, "content_type": content_type, "bytes": len(body), "created": now()}
        with self.store.lock:
            self.store.data["uploads"][uid] = rec
            self.store.save()
        return rec

    # ------------------------------------------------------------ jobs
    def submit(self, req: dict) -> dict:
        wf_id = str(req.get("workflow") or "")
        params = validate_params(wf_id, req.get("params") or {})
        wf = WORKFLOWS[wf_id]
        with self.store.lock:
            project_id = req.get("project_id")
            if project_id not in self.store.data["projects"]:
                raise ValidationError("Choose a project.")
            pending = sum(1 for j in self.store.data["jobs"].values() if j["status"] not in TERMINAL)
            if pending >= self.max_pending:
                raise ValidationError(f"The queue is full ({pending} jobs waiting). Wait for one to finish.")
            upload = self.store.data["uploads"].get(str(req.get("upload_id") or "")) if wf["requires_image"] else None
        if wf["requires_image"] and not upload:
            raise ValidationError("Upload a reference image first.")

        job_id = new_id()
        image_name = None
        if upload:
            with open(self.store.file("uploads", upload["id"] + upload["ext"]), "rb") as f:
                image_name = self.comfy.upload_image(f"{upload['id']}{upload['ext']}", f.read(), upload["content_type"])
        graph = build_graph(wf_id, params, image_name, f"studio/{job_id}")
        prompt_id = self.comfy.queue_prompt(graph)
        job = {
            "id": job_id, "project_id": project_id, "workflow": wf_id, "kind": wf["kind"], "model": wf["model"],
            "params": params, "upload_id": upload["id"] if upload else None, "prompt_id": prompt_id,
            "status": "queued", "stage": "Waiting in queue", "progress": None, "error": None,
            "created": now(), "started": None, "finished": None, "output": None,
        }
        with self.store.lock:
            self.store.data["jobs"][job_id] = job
            self.store.save()
        log(f"job {job_id} queued ({wf_id} {params['width']}x{params['height']} {params['frames']}f {params['steps']} steps)")
        return job

    def refresh(self) -> None:
        """Pulls real status from ComfyUI for every unfinished job. Runs in the background."""
        with self.store.lock:
            open_jobs = [dict(j) for j in self.store.data["jobs"].values() if j["status"] not in TERMINAL]
        if not open_jobs:
            return
        try:
            q = self.comfy.queue()
        except ComfyError:
            return  # ComfyUI offline: leave statuses as they are; the UI shows the studio as offline.
        running = {item[1] for item in q.get("queue_running", [])}
        pending = [item[1] for item in sorted(q.get("queue_pending", []), key=lambda i: i[0])]
        for job in open_jobs:
            pid = job["prompt_id"]
            update: dict = {}
            if pid in running:
                prog = self.comfy.progress_for(pid)
                update = {"status": "running", "started": job["started"] or now(), "position": 0,
                          "stage": STAGE_BY_NODE.get(str(prog.get("node")), "Working") if prog else "Starting",
                          "progress": {"value": prog["value"], "max": prog["max"]} if prog and prog["max"] else None}
            elif pid in pending:
                update = {"status": "queued", "position": pending.index(pid) + 1, "stage": f"Waiting in queue (#{pending.index(pid) + 1})"}
            else:
                try:
                    hist = self.comfy.history(pid)
                except ComfyError:
                    continue
                if hist is None:
                    # Not queued, not in history: ComfyUI restarted or the job was removed.
                    update = {"status": "failed", "finished": now(), "error": "ComfyUI lost this job (it may have restarted). Retry it."}
                else:
                    update = self._finish(job, hist)
            if update:
                with self.store.lock:
                    current = self.store.data["jobs"].get(job["id"])
                    if current and current["status"] not in TERMINAL:  # cancelled/deleted meanwhile → leave it
                        current.update(update)
                        self.store.save()

    def _finish(self, job: dict, hist: dict) -> dict:
        status = hist.get("status") or {}
        if status.get("status_str") == "error" or not status.get("completed", True):
            msg = "Generation failed."
            for m in status.get("messages") or []:
                if isinstance(m, list) and len(m) > 1 and m[0] in ("execution_error", "execution_interrupted"):
                    if m[0] == "execution_interrupted":
                        return {"status": "cancelled", "finished": now(), "stage": "Cancelled"}
                    msg = (m[1] or {}).get("exception_message") or msg
            if "out of memory" in msg.lower() or "OutOfMemory" in msg:
                msg = "The GPU ran out of memory. Try a draft size, fewer frames, or close other GPU apps. (" + msg.strip()[:200] + ")"
            log(f"job {job['id']} failed: {msg[:300]}")
            return {"status": "failed", "finished": now(), "error": msg[:1000], "stage": "Failed"}
        files = []
        for node_out in (hist.get("outputs") or {}).values():
            for items in node_out.values():
                if isinstance(items, list):
                    files += [i for i in items if isinstance(i, dict) and str(i.get("filename", "")).endswith((".mp4", ".webm", ".mkv"))]
        if not files:
            return {"status": "failed", "finished": now(), "error": "ComfyUI finished but produced no video file.", "stage": "Failed"}
        src = files[0]
        ext = os.path.splitext(src["filename"])[1]
        dest = self.store.file("outputs", job["id"] + ext)
        try:
            size = self.comfy.download_output(src["filename"], src.get("subfolder", ""), src.get("type", "output"), dest)
        except (ComfyError, OSError) as e:
            return {"status": "failed", "finished": now(), "error": f"Could not copy the video from ComfyUI: {e}"[:500]}
        check = self.validate_video(dest)
        if not check["ok"]:
            return {"status": "failed", "finished": now(), "error": "The output file is not a playable video: " + check["detail"]}
        log(f"job {job['id']} succeeded → {os.path.basename(dest)} ({size} bytes, {check['detail']})")
        return {"status": "succeeded", "finished": now(), "stage": "Done", "progress": None,
                "output": {"file": job["id"] + ext, "bytes": size, "mime": "video/mp4" if ext == ".mp4" else f"video/{ext[1:]}", **check["info"]}}

    def validate_video(self, path: str) -> dict:
        try:
            with open(path, "rb") as f:
                head = f.read(12)
        except OSError as e:
            return {"ok": False, "detail": str(e), "info": {}}
        if os.path.getsize(path) < 1024 or (path.endswith(".mp4") and head[4:8] != b"ftyp"):
            return {"ok": False, "detail": "file is empty or not an MP4 container", "info": {}}
        if not self.ffprobe:
            return {"ok": True, "detail": "container header checked (install FFmpeg for a full check)", "info": {}}
        try:
            r = subprocess.run([self.ffprobe, "-v", "error", "-select_streams", "v:0", "-show_entries", "stream=width,height,nb_frames,codec_name:format=duration",
                                "-of", "json", path], capture_output=True, timeout=30, text=True)
            meta = json.loads(r.stdout or "{}")
            stream = (meta.get("streams") or [{}])[0]
            if not stream.get("width"):
                return {"ok": False, "detail": "ffprobe found no video stream", "info": {}}
            info = {"width": stream["width"], "height": stream["height"], "codec": stream.get("codec_name"),
                    "duration_s": round(float(meta.get("format", {}).get("duration", 0)), 2)}
            return {"ok": True, "detail": f"ffprobe: {info['codec']} {info['width']}x{info['height']} {info['duration_s']}s", "info": info}
        except (OSError, ValueError, subprocess.SubprocessError) as e:
            return {"ok": True, "detail": f"header checked; ffprobe failed ({e})", "info": {}}

    def cancel(self, job_id: str) -> dict:
        with self.store.lock:
            job = self.store.data["jobs"].get(job_id)
        if not job:
            raise KeyError(job_id)
        if job["status"] in TERMINAL:
            return job
        try:
            q = self.comfy.queue()
            if any(i[1] == job["prompt_id"] for i in q.get("queue_running", [])):
                self.comfy.interrupt(job["prompt_id"])
            else:
                self.comfy.delete_pending(job["prompt_id"])
        except ComfyError as e:
            raise ValidationError(f"Could not reach ComfyUI to cancel: {e}") from None
        with self.store.lock:
            job.update({"status": "cancelled", "finished": now(), "stage": "Cancelled"})
            self.store.data["jobs"][job_id] = job
            self.store.save()
        return job

    def delete_job(self, job_id: str) -> None:
        with self.store.lock:
            job = self.store.data["jobs"].get(job_id)
            if not job:
                raise KeyError(job_id)
            if job["status"] not in TERMINAL:
                raise ValidationError("Cancel the job before deleting it.")
            if job.get("output"):
                try:
                    os.remove(self.store.file("outputs", job["output"]["file"]))
                except FileNotFoundError:
                    pass
            del self.store.data["jobs"][job_id]
            self.store.save()

    def background(self) -> None:
        while True:
            try:
                self.refresh()
            except Exception:
                log("refresh error:\n" + traceback.format_exc())
            time.sleep(2)


def _public_wf(wf: dict) -> dict:
    return {k: wf[k] for k in ("id", "kind", "label", "model", "license", "requires_image")}


def log(msg: str) -> None:
    print(time.strftime("%H:%M:%S"), msg, flush=True)


# ====================================================================== HTTP
class Handler(BaseHTTPRequestHandler):
    agent: Agent  # set on the class at startup
    server_version = "BlvckdiskStudioAgent/" + VERSION
    sys_version = ""

    def log_message(self, fmt, *args):  # keep tokens out of the console log
        pass

    # ---------------- plumbing
    def _cors(self) -> None:
        origin = self.headers.get("Origin")
        if origin and origin in self.agent.origins:
            self.send_header("Access-Control-Allow-Origin", origin)
            self.send_header("Vary", "Origin")
            self.send_header("Access-Control-Allow-Headers", "Authorization, Content-Type")
            self.send_header("Access-Control-Allow-Methods", "GET, POST, PATCH, DELETE, OPTIONS")
            self.send_header("Access-Control-Max-Age", "600")

    def _send(self, status: int, data=None) -> None:
        body = json.dumps(data if data is not None else {}).encode()
        self.send_response(status)
        self._cors()
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Cache-Control", "no-store")
        self.send_header("X-Content-Type-Options", "nosniff")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def _error(self, status: int, message: str) -> None:
        self._send(status, {"ok": False, "error": message})

    def _authorized(self, query: dict) -> bool:
        auth = self.headers.get("Authorization", "")
        token = auth[7:] if auth.startswith("Bearer ") else None
        if token is None and self.command == "GET":
            token = (query.get("t") or [None])[0]  # <video>/<img> cannot send headers
        return verify_token(self.agent.secret, token)

    def _body(self, limit: int) -> bytes:
        length = int(self.headers.get("Content-Length") or 0)
        if length > limit:
            raise ValidationError(f"Request too large (max {limit // (1024 * 1024) or 1} MB).")
        return self.rfile.read(length) if length else b""

    def _json(self) -> dict:
        try:
            data = json.loads(self._body(MAX_JSON) or b"{}")
        except ValueError:
            raise ValidationError("Invalid JSON.") from None
        if not isinstance(data, dict):
            raise ValidationError("Invalid JSON.")
        return data

    def do_OPTIONS(self):
        self.send_response(204)
        self._cors()
        self.end_headers()

    def do_GET(self):
        self._route()

    def do_POST(self):
        self._route()

    def do_PATCH(self):
        self._route()

    def do_DELETE(self):
        self._route()

    # ---------------- routes
    def _route(self) -> None:
        url = urlparse(self.path)
        query = parse_qs(url.query)
        parts = [p for p in url.path.split("/") if p]
        if not self._authorized(query):
            return self._error(401, "Not authorised. Sign in to the studio again.")
        a = self.agent
        m = self.command
        try:
            if parts == ["health"] and m == "GET":
                return self._send(200, {"ok": True, "agent": VERSION})
            if parts == ["capabilities"] and m == "GET":
                return self._send(200, a.capabilities())

            if parts == ["uploads"] and m == "POST":
                ctype = (self.headers.get("Content-Type") or "").split(";")[0].strip().lower()
                return self._send(201, a.save_upload(self._body(MAX_UPLOAD), ctype))
            if len(parts) == 2 and parts[0] == "uploads" and m == "GET":
                rec = a.store.data["uploads"].get(_id(parts[1]))
                if not rec:
                    return self._error(404, "Not found.")
                return self._file(a.store.file("uploads", rec["id"] + rec["ext"]), rec["content_type"])

            if parts == ["projects"] and m == "GET":
                with a.store.lock:
                    projects = sorted(a.store.data["projects"].values(), key=lambda p: -p["created"])
                    counts = {}
                    for j in a.store.data["jobs"].values():
                        counts[j["project_id"]] = counts.get(j["project_id"], 0) + 1
                return self._send(200, {"projects": [{**p, "jobs": counts.get(p["id"], 0)} for p in projects]})
            if parts == ["projects"] and m == "POST":
                name = _name(self._json().get("name"))
                pid = new_id()
                with a.store.lock:
                    a.store.data["projects"][pid] = {"id": pid, "name": name, "created": now()}
                    a.store.save()
                return self._send(201, a.store.data["projects"][pid])
            if len(parts) == 2 and parts[0] == "projects" and m in ("PATCH", "DELETE"):
                pid = _id(parts[1])
                with a.store.lock:
                    if pid not in a.store.data["projects"]:
                        return self._error(404, "Not found.")
                    if m == "PATCH":
                        a.store.data["projects"][pid]["name"] = _name(self._json().get("name"))
                        a.store.save()
                        return self._send(200, a.store.data["projects"][pid])
                    jobs = [j for j in a.store.data["jobs"].values() if j["project_id"] == pid]
                    if any(j["status"] not in TERMINAL for j in jobs):
                        raise ValidationError("This project has jobs in progress. Cancel them first.")
                    if len(a.store.data["projects"]) == 1:
                        raise ValidationError("Keep at least one project.")
                    for j in jobs:
                        a.delete_job(j["id"])
                    del a.store.data["projects"][pid]
                    a.store.save()
                return self._send(200, {"ok": True})

            if parts == ["jobs"] and m == "GET":
                pid = (query.get("project") or [None])[0]
                with a.store.lock:
                    jobs = [j for j in a.store.data["jobs"].values() if not pid or j["project_id"] == pid]
                return self._send(200, {"jobs": sorted(jobs, key=lambda j: -j["created"])[:200]})
            if parts == ["jobs"] and m == "POST":
                return self._send(201, a.submit(self._json()))
            if len(parts) >= 2 and parts[0] == "jobs":
                jid = _id(parts[1])
                if len(parts) == 2 and m == "GET":
                    job = a.store.data["jobs"].get(jid)
                    return self._send(200, job) if job else self._error(404, "Not found.")
                if len(parts) == 2 and m == "DELETE":
                    a.delete_job(jid)
                    return self._send(200, {"ok": True})
                if parts[2:] == ["cancel"] and m == "POST":
                    return self._send(200, a.cancel(jid))

            if len(parts) == 2 and parts[0] == "media" and m == "GET":
                job = a.store.data["jobs"].get(_id(parts[1]))
                if not job or not job.get("output"):
                    return self._error(404, "Not found.")
                download = (query.get("download") or ["0"])[0] == "1"
                return self._file(a.store.file("outputs", job["output"]["file"]), job["output"]["mime"],
                                  f"blvckdisk-studio-{job['id']}{os.path.splitext(job['output']['file'])[1]}" if download else None)
            return self._error(404, "Not found.")
        except KeyError:
            return self._error(404, "Not found.")
        except ValidationError as e:
            return self._error(400, str(e))
        except ComfyError as e:
            log(f"ComfyUI error: {e}")
            return self._error(502, str(e)[:800])
        except Exception:
            log("unexpected error:\n" + traceback.format_exc())
            return self._error(500, "Unexpected error on the studio computer. See the agent window for details.")

    def _file(self, path: str, mime: str, download_name: str | None = None) -> None:
        """Streams a file with HTTP Range support (needed for video seeking, especially on iPhone)."""
        try:
            size = os.path.getsize(path)
        except OSError:
            return self._error(404, "File missing on the studio computer.")
        start, end, status = 0, size - 1, 200
        rng = self.headers.get("Range")
        if rng:
            mt = re.match(r"bytes=(\d*)-(\d*)$", rng.strip())
            if mt and (mt.group(1) or mt.group(2)):
                if mt.group(1):
                    start = int(mt.group(1))
                    end = min(int(mt.group(2)), size - 1) if mt.group(2) else size - 1
                else:
                    start = max(0, size - int(mt.group(2)))
                if start > end or start >= size:
                    self.send_response(416)
                    self._cors()
                    self.send_header("Content-Range", f"bytes */{size}")
                    self.end_headers()
                    return
                status = 206
        self.send_response(status)
        self._cors()
        self.send_header("Content-Type", mime)
        self.send_header("Accept-Ranges", "bytes")
        self.send_header("Content-Length", str(end - start + 1))
        self.send_header("Cache-Control", "private, max-age=600")
        self.send_header("X-Content-Type-Options", "nosniff")
        if status == 206:
            self.send_header("Content-Range", f"bytes {start}-{end}/{size}")
        if download_name:
            self.send_header("Content-Disposition", f'attachment; filename="{download_name}"')
        self.end_headers()
        if self.command == "HEAD":
            return
        with open(path, "rb") as f:
            f.seek(start)
            left = end - start + 1
            try:
                while left > 0 and (chunk := f.read(min(1 << 20, left))):
                    self.wfile.write(chunk)
                    left -= len(chunk)
            except (BrokenPipeError, ConnectionResetError):
                pass


def _id(value: str) -> str:
    if not ID_RE.match(value or ""):
        raise KeyError(value)
    return value


def _name(value) -> str:
    name = re.sub(r"\s+", " ", str(value or "")).strip()[:80]
    if not name:
        raise ValidationError("Give the project a name.")
    return name


