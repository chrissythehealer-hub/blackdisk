def init_config(origin: str | None) -> None:
    if os.path.exists(CONFIG_PATH):
        print(f"config.json already exists at {CONFIG_PATH} — not overwriting it.")
        return
    origins = [o.strip().rstrip("/") for o in (origin or "").split(",") if o.strip()]
    cfg = {
        "secret": secrets.token_urlsafe(48),
        "allowed_origins": origins or ["http://localhost:4321"],
        "comfy_url": "http://127.0.0.1:8188",
        "host": "127.0.0.1",
        "port": 8787,
        "data_dir": "studio-data",
        "max_pending": 6,
    }
    with open(CONFIG_PATH, "w", encoding="utf-8") as f:
        json.dump(cfg, f, indent=2)
    print("Created config.json.\n")
    print("Copy this value into Vercel → Settings → Environment Variables as STUDIO_AGENT_SECRET:\n")
    print("   " + cfg["secret"] + "\n")
    print("Allowed website origins:", ", ".join(cfg["allowed_origins"]))
    print("Edit config.json to add your Vercel preview/production URLs to allowed_origins.")


def main() -> None:
    ap = argparse.ArgumentParser(description="BLVCKDISK AI Studio agent")
    ap.add_argument("--init", action="store_true", help="create config.json with a new secret")
    ap.add_argument("--origin", help="website origin(s) for --init, comma separated")
    ap.add_argument("--config", default=CONFIG_PATH)
    args = ap.parse_args()
    if args.init:
        return init_config(args.origin)
    if not os.path.exists(args.config):
        sys.exit("No config.json yet. Run:  python agent.py --init --origin https://your-site.vercel.app")
    with open(args.config, encoding="utf-8") as f:
        cfg = json.load(f)
    if len(cfg.get("secret", "")) < 32:
        sys.exit("config.json: secret must be at least 32 characters.")
    host = cfg.get("host", "127.0.0.1")
    if host not in ("127.0.0.1", "localhost", "::1"):
        log(f"WARNING: listening on {host}. Keep this on 127.0.0.1 and use the tunnel for remote access.")

    agent = Agent(cfg)
    Handler.agent = agent
    agent.comfy.start_progress_listener()
    threading.Thread(target=agent.background, name="refresh", daemon=True).start()
    server = ThreadingHTTPServer((host, int(cfg.get("port", 8787))), Handler)
    server.daemon_threads = True
    log(f"AI Studio agent {VERSION} on http://{host}:{cfg.get('port', 8787)}  (ComfyUI: {agent.comfy.base})")
    log("Allowed origins: " + ", ".join(sorted(agent.origins)))
    if not agent.ffprobe:
        log("FFmpeg/ffprobe not found on PATH — outputs get a basic check only.")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        log("Stopped.")


if __name__ == "__main__":
    main()
